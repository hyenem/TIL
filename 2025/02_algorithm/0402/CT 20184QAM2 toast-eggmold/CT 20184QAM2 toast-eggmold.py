N, L, R = map(int, input().split())
arr = [list(map(int, input().split())) for _ in range(N)]
dxdy = ((1, 0), (-1, 0), (0, 1), (0, -1))

time = 0
while True:
    block = 0
    # 이동을 미리 시키고 그 수로 비교해서 국격을 열면 안되니까
    # 이동하기 전 상황을 보고 국경 열지 말지 결정하기위해
    # 기존 배열을 하나 복사해둠
    tmparr = [ele[:] for ele in arr]

    visited = [[0]*N for _ in range(N)]
    for i in range(N):
        for j in range(N):

            # 이미 특정 나라랑 연결되었으면 넘어가기
            if visited[i][j]: continue

            block += 1
            # 국경이 열린 나라들끼리 인구의 합을 저장
            acc = tmparr[i][j]
            visited[i][j]=1
            q = [(i,j)]
            idx = 0
            while idx<len(q):
                x, y = q[idx]
                idx+=1
                for dx, dy in dxdy:
                    nx, ny = x+dx, y+dy
                    if not (0<=nx<N and 0<=ny<N): continue
                    if visited[nx][ny]: continue
                    # 범위 안이고, 방문 안했고,
                    # 지금 칸이랑 다음 칸의 차가 국경을 열 만큼이면
                    # 국경열기(인구누적, 방문표시, 큐에 추가)
                    if L<=abs(tmparr[x][y]-tmparr[nx][ny])<=R:
                        acc+=tmparr[nx][ny]
                        visited[nx][ny]=1
                        q.append((nx, ny))

            # 평균 인구수 계산하고, tmp배열이 아닌 실제 배열에 업데이트
            avg = acc//len(q)
            while q:
                x, y = q.pop()
                arr[x][y]=avg

    # block은 구분되어있는 국경의 계수
    # block이 n*n이라는건 bfs를 한번도 안 돌았다는 뜻
    # 즉 국경이 아예 안열렸으니까 이 경우 break
    if block == N*N: break

    # 국경이 하나라도 열린경우는 시간 하나 추가
    time += 1

print(time)
