N, L, R = map(int, input().split())
arr = [list(map(int, input().split())) for _ in range(N)]

end = 0
ans = -1
while not end:
    ans += 1
    end = 1
    visited = [[0]*N for _ in range(N)]
    for i in range(N):
        for j in range(N):
            if visited[i][j]: continue
            visited[i][j]=1
            q = [(i, j)]
            idx = 0
            summ = arr[i][j]

            while idx<len(q):
                x, y = q[idx]
                idx += 1

                for dx, dy in ((-1, 0), (0, 1), (1, 0), (0, -1)):
                    nx, ny = x+dx, y+dy
                    if not(0<=nx<N and 0<=ny<N): continue
                    if visited[nx][ny]: continue
                    if L<=abs(arr[x][y]- arr[nx][ny])<=R:
                        visited[nx][ny]=1
                        q.append((nx, ny))
                        summ+=arr[nx][ny]

            if len(q)==1: continue

            end = 0
            amount = summ//len(q)
            for x, y in q:
                arr[x][y]=amount

print(ans)

